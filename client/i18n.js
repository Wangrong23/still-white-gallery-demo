export const language =
  localStorage.getItem("still.language") === "en" ? "en" : "zh";

export const t = (key) => copy[language][key] ?? key;

export const tf = (key, values) =>
  Object.entries(values).reduce(
    (value, [name, replacement]) => value.replace(`{${name}}`, replacement),
    t(key),
  );

export function translateError(message) {
  const errors = {
    "服务器房间已满，请稍后重试。": "serverFull",
    "房间不存在、已满或游戏已经开始。": "roomUnavailable",
    "请求格式无效。": "invalidRequest",
  };
  return t(errors[message] || message);
}

export function applyLanguage() {
  document.documentElement.lang = language === "zh" ? "zh-CN" : "en";
  document.title = t("title");
  const text = {
    "#edition-copy": "edition",
    "#study-copy": "study",
    "#volume-copy": "volume",
    ".title .eyebrow": "gallery",
    ".title h1": "gameName",
    ".intro": "intro",
    '[data-role="detective"]': "detective",
    '[data-role="killer"]': "killer",
    "#join-form label": "roomCode",
    "#connect": "connect",
    "#help-button": "helpButton",
    "#network-cancel": "leaveRoom",
    "#pause .eyebrow": "gameName",
    "#pause h2": "pauseTitle",
    "#pause-copy": "pauseCopy",
    "#resume": "continue",
    "#return-menu": "returnMenu",
    "#pause summary": "instructions",
    "#replay": "replay",
    "#result-menu": "returnMenu",
    "#help .eyebrow": "fieldNotes",
    "#help h2": "helpTitle",
  };
  for (const [selector, key] of Object.entries(text)) {
    const el = document.querySelector(selector);
    if (el) el.textContent = t(key);
  }
  const html = {
    ".title-bottom": `<span class="chinese">${t("gameName")}</span><span>${t("tagline")}</span>`,
    "#local": t("local"),
    "#host": t("host"),
    "#join": t("join"),
    ".menu-note": t("note"),
  };
  for (const [selector, value] of Object.entries(html)) {
    const el = document.querySelector(selector);
    if (el) el.innerHTML = value;
  }
  document.querySelectorAll(".help-copy").forEach((el) => (el.innerHTML = t("help")));
  document.querySelector(".play-menu")?.setAttribute("aria-label", t("playAria"));
  document.querySelector("#game")?.setAttribute("aria-label", t("canvasAria"));
  document.querySelector("#pause-button")?.setAttribute("aria-label", t("pauseAria"));
  document.querySelector("#close-help")?.setAttribute("aria-label", t("close"));
  const select = document.querySelector("#language");
  if (select) select.value = language;
}
